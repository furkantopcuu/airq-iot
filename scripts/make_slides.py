"""Render the slide material from its sources (TALIMAT 12): numbers come from paper/numbers.tex.

    slides/src/outline.src.md -> slides/outline.md   (titles, bullets, why-boxes, figures)
    slides/src/notes.src.md   -> slides/notes.md     (speaker notes: key points, no script)
    slides/src/qa.src.md      -> slides/qa.md        (likely jury questions, short honest answers)

A `{{nName}}` placeholder is replaced by the macro of the same name in paper/numbers.tex, which
is generated from reports/, so a number on a slide is the number in the paper and in the results
files. An unknown placeholder is an error.

    python -m scripts.make_slides          # write the three files
    python -m scripts.make_slides --check  # fail if the committed files are out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "slides" / "src"
OUT = ROOT / "slides"
NAMES = ("outline", "notes", "qa", "hazirlik")
HEADER = (
    "<!-- Generated by scripts/make_slides.py from slides/src/{name}.src.md and paper/numbers.tex. "
    "Do not edit by hand. -->\n\n"
)


def macros() -> dict[str, str]:
    text = (ROOT / "paper" / "numbers.tex").read_text(encoding="utf-8")
    return dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", text))


def render(name: str, values: dict[str, str]) -> str:
    text = (SRC / f"{name}.src.md").read_text(encoding="utf-8")

    def sub(m: re.Match) -> str:
        key = m.group(1)
        if key not in values:
            raise KeyError(f"{name}.src.md: unknown number placeholder {{{{{key}}}}}")
        return values[key]

    return HEADER.format(name=name) + re.sub(r"\{\{(\w+)\}\}", sub, text)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--check", action="store_true", help="fail if the committed files are out of date"
    )
    args = ap.parse_args()
    values = macros()
    stale = []
    for name in NAMES:
        text = render(name, values)
        target = OUT / f"{name}.md"
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(target.name)
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote slides/{name}.md ({len(text.splitlines())} lines)")
    if args.check:
        print("slides are up to date" if not stale else f"OUT OF DATE: {', '.join(stale)}")
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
